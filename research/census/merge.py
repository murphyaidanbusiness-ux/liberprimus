"""Merge the exhaustion-census parts into one table, applying the orchestrator's judgments (judgments.tsv, written by
write_judgments.py: a verdict, a bucket and any re-grade for every row). Writes research/census/merged.md;
research/EXHAUSTED.md is written by hand from it. Fails if any row has no judgment, or a judgment has no row.

    python research/census/write_judgments.py && python research/census/merge.py
"""
import re
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
PARTS = ["dukotah.md", "repos.md", "aldegonde2.md", "web.md"]
BUCKETS = [("dead", "closed: dead by a constraint"), ("full", "closed: searched in full"),
           ("test", "closed: refuted by a direct test"), ("probe", "structure probe (not a key search)"),
           ("open", "open-ended key space"), ("off", "off-stream (images, payloads, hashes, readings)"),
           ("partial", "partial, finite: candidate to reopen")]
SHORT = {"dead": "closed", "full": "closed", "test": "closed", "probe": "probe", "open": "open-ended",
         "off": "off-stream", "partial": "partial"}


def rows_of(path):
    text = path.read_text(encoding="utf-8")
    m = re.search(r"(?ms)^##\s+Census[^\n]*\n(.*?)(?=^##\s|\Z)", text)
    out = []
    for line in (m.group(1) if m else "").splitlines():
        if not line.startswith("|") or re.match(r"^\|\s*:?-", line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 10 and cells[0].lower() != "id":
            out.append(dict(zip(["id", "method", "family", "scope", "control", "null", "source", "strength",
                                 "coverage", "constraint"], cells), part=path.name))
    return out


def load_judgments():
    lines = (HERE / "judgments.tsv").read_text(encoding="utf-8").splitlines()
    head = lines[0].split("\t")
    return {d["id"]: d for d in (dict(zip(head, l.split("\t"))) for l in lines[1:] if l.strip())}


def main():
    rows = []
    for name in PARTS:
        if (HERE / name).exists():
            rows += rows_of(HERE / name)
    J = load_judgments()
    missing = [r["id"] for r in rows if r["id"] not in J]
    extra = sorted(set(J) - {r["id"] for r in rows})
    if missing or extra:
        raise SystemExit("judgments do not match the rows: missing %s, extra %s" % (missing, extra))
    for r in rows:
        j = J[r["id"]]
        if j["constraint"]:
            r["was"], r["constraint"] = r["constraint"], j["constraint"] + " [orchestrator re-grade]"
        if j["strength"]:
            r["was_strength"], r["strength"] = r["strength"], j["strength"]
        r["bucket"], r["note"] = j["bucket"], j["note"]
    by = defaultdict(list)
    for r in rows:
        by[r["bucket"]].append(r)
    agree = sum(J[r["id"]]["verdict"] == "agree" for r in rows)
    lines = ["# Exhaustion census, merged (generated by research/census/merge.py)", "",
             "Parts: %s. %d rows, every one judged by the orchestrator (%d agree, %d re-graded; `judgments.tsv`)." % (
                 ", ".join(p for p in PARTS if (HERE / p).exists()), len(rows), agree, len(rows) - agree), "",
             "| bucket | rows | strength A/B/C/D |", "|---|---|---|"]
    for key, label in BUCKETS:
        c = Counter(r["strength"] for r in by[key])
        lines.append("| %s | %d | %d/%d/%d/%d |" % (label, len(by[key]), c["A"], c["B"], c["C"], c["D"]))
    cols = ["closed", "probe", "open-ended", "off-stream", "partial"]
    fam = Counter((r["family"], SHORT[r["bucket"]]) for r in rows)
    lines += ["", "## By family", "", "| family | " + " | ".join(cols) + " |", "|---" * (len(cols) + 1) + "|"]
    for f in sorted({r["family"] for r in rows}):
        lines.append("| %s | " % f + " | ".join(str(fam[(f, c)]) for c in cols) + " |")
    lines += ["", "## Re-graded by the orchestrator", ""]
    for r in rows:
        if "was" in r:
            lines.append("- %s (%s): was `%s`; now `%s`" % (r["id"], r["method"][:70], r["was"][:90],
                                                          J[r["id"]]["constraint"]))
        if "was_strength" in r:
            lines.append("- %s: strength %s -> %s (%s)" % (r["id"], r["was_strength"], r["strength"], r["note"]))
    for key, label in BUCKETS:
        lines += ["", "## " + label, "",
                  "| id | method | family | scope | control | null | strength | coverage | constraint | orchestrator note | source |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(by[key], key=lambda r: r["id"]):
            lines.append("| " + " | ".join([r["id"], r["method"], r["family"], r["scope"], r["control"], r["null"],
                                            r["strength"], r["coverage"], r["constraint"], r["note"] or "-",
                                            r["source"]]) + " |")
    (HERE / "merged.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    for key, label in BUCKETS:
        ids = " ".join(sorted(r["id"] for r in by[key])) if key == "partial" else ""
        print("%-50s %3d  %s" % (label, len(by[key]), ids))
    print("rows %d, agree %d, re-graded %d" % (len(rows), agree, len(rows) - agree))


if __name__ == "__main__":
    main()
